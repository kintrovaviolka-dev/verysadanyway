// Stage only browser assets for Vercel and Cloudflare. Never publish the repository root.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, '.public-build');
const marker = path.join(output, '.generated-public-assets');
if (fs.existsSync(output)) {
  if (!fs.existsSync(marker)) throw new Error('Refusing to replace an unmarked output directory');
  fs.rmSync(output, { recursive: true });
}
fs.mkdirSync(output);
fs.writeFileSync(marker, 'Generated by scripts/build_public.cjs\n');
const forbidden = /^(?:node_modules|src|raw|img_src|test|tests|e2e|tools|scripts|private-patient|dist|\.git|\.env.*|server\..*|package.*|tsconfig.*|vite\.config.*|playwright\.config.*)$/;
// Match the existing deployment policy: reference PDFs and editable documents
// are source material, not browser assets.
const extensions = /\.(?:html|css|mjs|js|json|svg|png|jpg|jpeg|webp|gif|ico|woff2?|ttf|mp3|mp4|webm|wasm|webmanifest|md)$/i;
function copyTree(source, target) {
  fs.mkdirSync(target, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || forbidden.test(entry.name) || entry.isSymbolicLink()) continue;
    const from = path.join(source, entry.name), to = path.join(target, entry.name);
    if (entry.isDirectory()) copyTree(from, to);
    else if (extensions.test(entry.name) && !/\.(?:test|spec)\.js$/.test(entry.name)) fs.copyFileSync(from, to);
  }
}
for (const name of ['index.html', 'style.css', 'app.js', 'feedback.js', 'cases.js', 'data_pathology.js', 'data_pathology_zapocet.js', 'data_patfyz_bridge.js']) fs.copyFileSync(path.join(root, name), path.join(output, name));
for (const name of ['aro', 'ctvrtak', 'derma', 'drill', 'farmakologie', 'imunologie-test', 'kardio', 'mikra', 'neuro', 'oset', 'podcast', 'psych', 'radiolka', 'upv', 'usg-school']) {
  if (fs.existsSync(path.join(root, name))) copyTree(path.join(root, name), path.join(output, name));
}
for (const name of ['clinical-learning-portal', 'urgentni-prijem']) {
  const source = path.join(root, name, 'dist');
  if (!fs.existsSync(path.join(source, 'index.html'))) throw new Error(`Build ${name} before staging public assets`);
  copyTree(source, path.join(output, name));
}
if (fs.existsSync(path.join(root, 'private-patient', 'LICENSE'))) {
  fs.mkdirSync(path.join(output, 'third-party/ai-patient'), { recursive: true });
  for (const name of ['LICENSE', 'NOTICE']) {
    if (fs.existsSync(path.join(root, 'private-patient', name))) {
      fs.copyFileSync(path.join(root, 'private-patient', name), path.join(output, 'third-party/ai-patient', `${name}.txt`));
    }
  }
}
console.log('Public assets staged for deployment; server sources and reference materials excluded.');
